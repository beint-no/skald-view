import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
const metadata = JSON.parse(
  execFileSync(
    "cargo",
    [
      "metadata",
      "--locked",
      "--format-version",
      "1",
      "--filter-platform",
      "wasm32-unknown-unknown",
    ],
    { encoding: "utf8" },
  ),
);
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const visited = new Set();
function visit(id) {
  if (visited.has(id)) return;
  visited.add(id);
  for (const dep of nodes.get(id).deps)
    if (dep.dep_kinds.some((k) => k.kind !== "dev")) visit(dep.pkg);
}
visit(metadata.resolve.root);
let output =
  "Third-party notices for the locked Skald View WASM build.\nGenerated by scripts/licenses.mjs; includes build-time dependencies.\n";
for (const id of [...visited].sort()) {
  const p = packages.get(id);
  if (p.name === "skald-view") continue;
  output += `\n${"=".repeat(72)}\n${p.name} ${p.version}\nLicense: ${p.license ?? "see source"}\n${p.repository ?? p.source ?? ""}\n`;
  const directory = dirname(p.manifest_path);
  const files = readdirSync(directory).filter((f) =>
    /^(license|copying|notice)([-.]|$)/i.test(f),
  );
  if (p.license_file) files.push(p.license_file);
  for (const f of [...new Set(files)].sort()) {
    try {
      output += `\n--- ${f} ---\n${readFileSync(join(directory, f), "utf8")}\n`;
    } catch {}
  }
}
writeFileSync("docs/licenses/THIRD-PARTY.txt", output);
writeFileSync("web/pkg/THIRD-PARTY.txt", output);
